#define BIN_TEAM_NAME_LEN    20u
#define BIN_PLAYER_NAME_LEN  16u
#define BIN_COACH_NAME_LEN   20u
#define BIN_PLAYER_REC_SIZE  24u
#define BIN_TEAM_REC_SIZE    26u
#define BIN_TEAM_BLOCK_SIZE  (BIN_TEAM_REC_SIZE + PLAYERS_PER_TEAM * BIN_PLAYER_REC_SIZE)
#define BIN_TEAMS_HDR_SIZE    4u
#define BIN_COACHES_HDR_SIZE  2u
#define BIN_COACH_REC_SIZE   20u

static u8 nat_from_code(const u8 *c) {
    if (c[0]=='P'&&c[1]=='O'&&c[2]=='R') return 0u;
    if (c[0]=='B'&&c[1]=='R'&&c[2]=='A') return 1u;
    if (c[0]=='A'&&c[1]=='R'&&c[2]=='G') return 2u;
    if (c[0]=='E'&&c[1]=='S'&&c[2]=='P') return 3u;
    if (c[0]=='I'&&c[1]=='N'&&c[2]=='G') return 4u;
    if (c[0]=='F'&&c[1]=='R'&&c[2]=='A') return 5u;
    if (c[0]=='I'&&c[1]=='T'&&c[2]=='A') return 6u;
    if (c[0]=='A'&&c[1]=='L'&&c[2]=='E') return 7u;
    if (c[0]=='S'&&c[1]=='E'&&c[2]=='R') return 8u;
    if (c[0]=='J'&&c[1]=='U'&&c[2]=='G') return 8u;
    if (c[0]=='C'&&c[1]=='R'&&c[2]=='O') return 9u;
    return 0u;
}

static void copy_name(char *dst, const u8 *src, u8 dst_len) {
    u8 i;
    for (i = 0u; i < (u8)(dst_len - 1u); i++) {
        if (src[i] == 0u) break;
        dst[i] = (char)src[i];
    }
    dst[i] = '\0';
}

